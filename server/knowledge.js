const STOP = new Set(
  "the and for your you are with that this how what about help make me my from into just can".split(" "),
)

export function retrieve(query, limit = 3) {
  const q = normalize(query)
  if (!q) return []

  const scored = knowledge.map((item) => {
    let score = 0
    const hay = normalize(`${item.title} ${item.tags.join(" ")} ${item.body}`)
    for (const tag of item.tags) {
      const t = normalize(tag)
      if (q.includes(t) || t.split(" ").every((w) => q.includes(w))) {
        score += 8 + t.length
      }
    }
    for (const word of q.split(" ")) {
      if (word.length < 4 || STOP.has(word)) continue
      if (hay.includes(word)) score += 1
    }
    if (item.id === "wellbeing" && /(suicid|kill myself|end my life|self harm|hopeless)/.test(q)) {
      score += 50
    }
    return { item, score }
  })

  return scored
    .filter((x) => x.score > 8)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.item)
}

export function normalize(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[^a-z0-9%\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}
